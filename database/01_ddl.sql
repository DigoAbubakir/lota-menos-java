CREATE TABLE T_LM_LINHA (
    ID_LINHA      NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NR_LINHA      NUMBER(2)     NOT NULL,
    NM_LINHA      VARCHAR2(40)  NOT NULL,
    DS_COR        VARCHAR2(7)   NOT NULL,
    DS_OPERADORA  VARCHAR2(10)  NOT NULL,
    CONSTRAINT PK_LM_LINHA PRIMARY KEY (ID_LINHA),
    CONSTRAINT UK_LM_LINHA_NUMERO UNIQUE (NR_LINHA),
    CONSTRAINT CK_LM_LINHA_OPERADORA CHECK (DS_OPERADORA IN ('METRO', 'CPTM')),
    CONSTRAINT CK_LM_LINHA_COR CHECK (REGEXP_LIKE(DS_COR, '^#[0-9A-Fa-f]{6}$')),
    CONSTRAINT CK_LM_LINHA_NUMERO CHECK (NR_LINHA > 0)
);

CREATE TABLE T_LM_ESTACAO (
    ID_ESTACAO     NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NM_ESTACAO     VARCHAR2(60) NOT NULL,
    ST_INTEGRACAO  NUMBER(1)    DEFAULT 0 NOT NULL,
    ST_ATIVA       NUMBER(1)    DEFAULT 1 NOT NULL,
    CONSTRAINT PK_LM_ESTACAO PRIMARY KEY (ID_ESTACAO),
    CONSTRAINT UK_LM_ESTACAO_NOME UNIQUE (NM_ESTACAO),
    CONSTRAINT CK_LM_EST_INTEGRACAO CHECK (ST_INTEGRACAO IN (0, 1)),
    CONSTRAINT CK_LM_EST_ATIVA CHECK (ST_ATIVA IN (0, 1))
);

CREATE TABLE T_LM_LINHA_ESTACAO (
    ID_LINHA_ESTACAO  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_LINHA          NUMBER    NOT NULL,
    ID_ESTACAO        NUMBER    NOT NULL,
    NR_ORDEM          NUMBER(3) NOT NULL,
    CONSTRAINT PK_LM_LINHA_ESTACAO PRIMARY KEY (ID_LINHA_ESTACAO),
    CONSTRAINT FK_LM_LE_LINHA FOREIGN KEY (ID_LINHA) REFERENCES T_LM_LINHA (ID_LINHA),
    CONSTRAINT FK_LM_LE_ESTACAO FOREIGN KEY (ID_ESTACAO) REFERENCES T_LM_ESTACAO (ID_ESTACAO),
    CONSTRAINT UK_LM_LE_LINHA_ESTACAO UNIQUE (ID_LINHA, ID_ESTACAO),
    CONSTRAINT UK_LM_LE_LINHA_ORDEM UNIQUE (ID_LINHA, NR_ORDEM),
    CONSTRAINT CK_LM_LE_ORDEM CHECK (NR_ORDEM > 0)
);

CREATE TABLE T_LM_HISTORICO_LOTACAO (
    ID_HISTORICO  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_ESTACAO    NUMBER       NOT NULL,
    ID_LINHA      NUMBER       NOT NULL,
    DS_SENTIDO    VARCHAR2(20) NOT NULL,
    DS_TIPO_DIA   VARCHAR2(10) NOT NULL,
    HR_FAIXA      VARCHAR2(5)  NOT NULL,
    NR_INDICE     NUMBER(3)    NOT NULL,
    CONSTRAINT PK_LM_HISTORICO PRIMARY KEY (ID_HISTORICO),
    CONSTRAINT FK_LM_HIST_ESTACAO FOREIGN KEY (ID_ESTACAO) REFERENCES T_LM_ESTACAO (ID_ESTACAO),
    CONSTRAINT FK_LM_HIST_LINHA FOREIGN KEY (ID_LINHA) REFERENCES T_LM_LINHA (ID_LINHA),
    CONSTRAINT UK_LM_HIST_CHAVE UNIQUE (ID_ESTACAO, ID_LINHA, DS_SENTIDO, DS_TIPO_DIA, HR_FAIXA),
    CONSTRAINT CK_LM_HIST_SENTIDO CHECK (DS_SENTIDO IN ('SENTIDO_BARRA_FUNDA', 'SENTIDO_ITAQUERA')),
    CONSTRAINT CK_LM_HIST_TIPO_DIA CHECK (DS_TIPO_DIA IN ('UTIL', 'SABADO', 'DOMINGO')),
    CONSTRAINT CK_LM_HIST_FAIXA CHECK (REGEXP_LIKE(HR_FAIXA, '^([01][0-9]|2[0-3]):(00|15|30|45)$')),
    CONSTRAINT CK_LM_HIST_INDICE CHECK (NR_INDICE BETWEEN 0 AND 100)
);

CREATE TABLE T_LM_USUARIO (
    ID_USUARIO    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    NM_USUARIO    VARCHAR2(100) NOT NULL,
    DS_EMAIL      VARCHAR2(120) NOT NULL,
    DS_PERFIL     VARCHAR2(25)  NOT NULL,
    VL_REPUTACAO  NUMBER(3,2)   DEFAULT 1.0 NOT NULL,
    DT_CADASTRO   TIMESTAMP     NOT NULL,
    CONSTRAINT PK_LM_USUARIO PRIMARY KEY (ID_USUARIO),
    CONSTRAINT UK_LM_USUARIO_EMAIL UNIQUE (DS_EMAIL),
    CONSTRAINT CK_LM_USU_PERFIL CHECK (DS_PERFIL IN ('TRABALHADOR', 'IDOSO', 'MOBILIDADE_REDUZIDA', 'ESTUDANTE')),
    CONSTRAINT CK_LM_USU_REPUTACAO CHECK (VL_REPUTACAO BETWEEN 0.3 AND 1.5)
);

CREATE TABLE T_LM_RELATO_LOTACAO (
    ID_RELATO   NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO  NUMBER       NOT NULL,
    ID_ESTACAO  NUMBER       NOT NULL,
    ID_LINHA    NUMBER       NOT NULL,
    DS_SENTIDO  VARCHAR2(20) NOT NULL,
    DS_NIVEL    VARCHAR2(10) NOT NULL,
    DT_RELATO   TIMESTAMP    NOT NULL,
    CONSTRAINT PK_LM_RELATO PRIMARY KEY (ID_RELATO),
    CONSTRAINT FK_LM_REL_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_LM_USUARIO (ID_USUARIO),
    CONSTRAINT FK_LM_REL_ESTACAO FOREIGN KEY (ID_ESTACAO) REFERENCES T_LM_ESTACAO (ID_ESTACAO),
    CONSTRAINT FK_LM_REL_LINHA FOREIGN KEY (ID_LINHA) REFERENCES T_LM_LINHA (ID_LINHA),
    CONSTRAINT CK_LM_REL_SENTIDO CHECK (DS_SENTIDO IN ('SENTIDO_BARRA_FUNDA', 'SENTIDO_ITAQUERA')),
    CONSTRAINT CK_LM_REL_NIVEL CHECK (DS_NIVEL IN ('VAZIO', 'MODERADO', 'CHEIO', 'LOTADO'))
);

CREATE TABLE T_LM_CONSULTA_VIAGEM (
    ID_CONSULTA          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    ID_USUARIO           NUMBER       NOT NULL,
    ID_ESTACAO_ORIGEM    NUMBER       NOT NULL,
    ID_ESTACAO_DESTINO   NUMBER       NOT NULL,
    DS_SENTIDO           VARCHAR2(20) NOT NULL,
    DT_VIAGEM            DATE         NOT NULL,
    HR_DESEJADO          VARCHAR2(5)  NOT NULL,
    HR_SUGERIDO          VARCHAR2(5)  NOT NULL,
    NR_INDICE_DESEJADO   NUMBER(3)    NOT NULL,
    NR_INDICE_SUGERIDO   NUMBER(3)    NOT NULL,
    ID_ESTACAO_CRITICA   NUMBER,
    ST_SUGESTAO_ACEITA   NUMBER(1),
    DT_CONSULTA          TIMESTAMP    NOT NULL,
    CONSTRAINT PK_LM_CONSULTA PRIMARY KEY (ID_CONSULTA),
    CONSTRAINT FK_LM_CON_USUARIO FOREIGN KEY (ID_USUARIO) REFERENCES T_LM_USUARIO (ID_USUARIO),
    CONSTRAINT FK_LM_CON_ORIGEM FOREIGN KEY (ID_ESTACAO_ORIGEM) REFERENCES T_LM_ESTACAO (ID_ESTACAO),
    CONSTRAINT FK_LM_CON_DESTINO FOREIGN KEY (ID_ESTACAO_DESTINO) REFERENCES T_LM_ESTACAO (ID_ESTACAO),
    CONSTRAINT FK_LM_CON_CRITICA FOREIGN KEY (ID_ESTACAO_CRITICA) REFERENCES T_LM_ESTACAO (ID_ESTACAO),
    CONSTRAINT CK_LM_CON_SENTIDO CHECK (DS_SENTIDO IN ('SENTIDO_BARRA_FUNDA', 'SENTIDO_ITAQUERA')),
    CONSTRAINT CK_LM_CON_IND_DES CHECK (NR_INDICE_DESEJADO BETWEEN 0 AND 100),
    CONSTRAINT CK_LM_CON_IND_SUG CHECK (NR_INDICE_SUGERIDO BETWEEN 0 AND 100),
    CONSTRAINT CK_LM_CON_ACEITA CHECK (ST_SUGESTAO_ACEITA IN (0, 1)),
    CONSTRAINT CK_LM_CON_ORIG_DEST CHECK (ID_ESTACAO_ORIGEM <> ID_ESTACAO_DESTINO)
);

CREATE INDEX IX_LM_REL_ESTACAO_DATA ON T_LM_RELATO_LOTACAO (ID_ESTACAO, ID_LINHA, DS_SENTIDO, DT_RELATO);
CREATE INDEX IX_LM_REL_USUARIO_DATA ON T_LM_RELATO_LOTACAO (ID_USUARIO, ID_ESTACAO, DT_RELATO);
