BEGIN
    FOR t IN (SELECT column_value AS nome FROM TABLE(sys.odcivarchar2list(
                  'T_LM_CONSULTA_VIAGEM', 'T_LM_RELATO_LOTACAO', 'T_LM_HISTORICO_LOTACAO',
                  'T_LM_USUARIO', 'T_LM_LINHA_ESTACAO', 'T_LM_ESTACAO', 'T_LM_LINHA'))) LOOP
        BEGIN
            EXECUTE IMMEDIATE 'DROP TABLE ' || t.nome || ' CASCADE CONSTRAINTS PURGE';
        EXCEPTION
            WHEN OTHERS THEN
                IF SQLCODE != -942 THEN
                    RAISE;
                END IF;
        END;
    END LOOP;
END;
